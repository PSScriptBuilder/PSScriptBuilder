using namespace System
using namespace System.Collections.Generic
using namespace System.IO

#region Class PSScriptBuilderSourceMapFileManager
<#
.SYNOPSIS
    Manages reading and writing source map sidecar files.
.DESCRIPTION
    The PSScriptBuilderSourceMapFileManager provides static methods for writing and reading
    source map sidecar files (.sourcemap.json). The sidecar file stores a source map
    generated by PSScriptBuilderSourceMapGenerator alongside the SHA256 hash of the
    output script, allowing PSScriptBuilderSourceLocationResolver to detect stale maps.
#>
class PSScriptBuilderSourceMapFileManager {
    #region Static Fields
    <#
    .SYNOPSIS
        The file suffix appended to the output script path to derive the sidecar path.
    .DESCRIPTION
        Used by GetSidecarPath() to construct the .sourcemap.json path from any output script path.
    #>
    hidden static [string] $SourceMapSuffix = ".sourcemap.json"
    #endregion Static Fields

    #region Static Methods
    <#
    .SYNOPSIS
        Returns the sidecar path for a given output script path.
    .DESCRIPTION
        The GetSidecarPath method appends the ".sourcemap.json" suffix to the provided
        output path to derive the path of the corresponding sidecar file.
    .PARAMETER outputPath
        The absolute path to the built output script.
    .OUTPUTS
        Returns the sidecar path for the given output script path as string.
    #>
    static [string] GetSidecarPath([string] $outputPath) {
        if ([string]::IsNullOrWhiteSpace($outputPath)) {
            $message = "Parameter 'outputPath' cannot be null or empty."
            throw [ArgumentException]::new($message, "outputPath")
        }

        return $outputPath + [PSScriptBuilderSourceMapFileManager]::SourceMapSuffix
    }

    <#
    .SYNOPSIS
        Writes the complete source map data to a sidecar file alongside the output script.
    .DESCRIPTION
        The WriteSourceMapData method computes the SHA256 hash and line count of the output
        script, wraps all data in a PSCustomObject with PascalCase keys, serializes it as
        JSON, and writes it to the sidecar path derived from outputPath.
        Written using UTF-8 without BOM via PSScriptBuilderFileIOHelper.
    .PARAMETER outputPath
        The absolute path to the built output script.
    .PARAMETER sourceMap
        The source map components to write.
    #>
    static [void] WriteSourceMapData([string] $outputPath, [PSScriptBuilderSourceLocation[]] $sourceMap) {
        if ([string]::IsNullOrWhiteSpace($outputPath)) {
            $message = "Parameter 'outputPath' cannot be null or empty."
            throw [ArgumentException]::new($message, "outputPath")
        }

        if ($null -eq $sourceMap) {
            $message = "Parameter 'sourceMap' cannot be null."
            throw [ArgumentException]::new($message, "sourceMap")
        }

        $sidecarPath     = [PSScriptBuilderSourceMapFileManager]::GetSidecarPath($outputPath)
        $outputHash      = (Get-FileHash -LiteralPath $outputPath -Algorithm SHA256).Hash
        $outputLineCount = [File]::ReadAllLines($outputPath).Length

        Write-Verbose "Writing source map to: $sidecarPath"

        $components = [List[PSCustomObject]]::new()
        foreach ($entry in $sourceMap) {
            $components.Add([PSCustomObject] @{
                ComponentName       = $entry.ComponentName
                ComponentType       = $entry.ComponentType
                OutputLineNumber    = $entry.OutputLineNumber
                Offset              = $entry.Offset
                SourceFile          = $entry.SourceFile
                ComponentLineNumber = $entry.ComponentLineNumber
                SourceLineNumber    = $entry.SourceLineNumber
            })
        }

        $data = [PSCustomObject] @{
            OutputPath      = $outputPath
            OutputHash      = $outputHash
            OutputLineCount = $outputLineCount
            Components      = $components.ToArray()
        }

        try {
            $json = $data | ConvertTo-Json -Depth 5
            [PSScriptBuilderFileIOHelper]::WriteAllTextUTF8WithoutBOM($sidecarPath, $json)
            Write-Verbose "  Source map written: $($sourceMap.Count) component(s)"
        }
        catch {
            $format  = "Failed to write source map to: {0}. Error: {1}"
            $message = $format -f $sidecarPath, $_.Exception.Message
            throw [IOException]::new($message, $_.Exception)
        }
    }

    <#
    .SYNOPSIS
        Reads the complete source map data from a sidecar file.
    .DESCRIPTION
        The ReadSourceMapData method parses the sidecar JSON file at the given path and
        returns a PSScriptBuilderSourceMapData instance containing the output path, SHA-256
        hash, total line count, and the reconstructed source location entries.
        Throws FileNotFoundException if the sidecar file does not exist.
    .PARAMETER sidecarPath
        The absolute path to the sidecar file.
    .OUTPUTS
        Returns the deserialized sidecar content as PSScriptBuilderSourceMapData.
    #>
    static [PSScriptBuilderSourceMapData] ReadSourceMapData([string] $sidecarPath) {
        if ([string]::IsNullOrWhiteSpace($sidecarPath)) {
            $message = "Parameter 'sidecarPath' cannot be null or empty."
            throw [ArgumentException]::new($message, "sidecarPath")
        }

        if (-not [File]::Exists($sidecarPath)) {
            $format  = "Source map not found: {0}. Run Invoke-PSScriptBuilderBuild with -WriteSourceMap to generate one."
            $message = $format -f $sidecarPath
            throw [FileNotFoundException]::new($message, $sidecarPath)
        }

        Write-Verbose "Reading source map from: $sidecarPath"

        try {
            $json   = [File]::ReadAllText($sidecarPath)
            $data   = $json | ConvertFrom-Json
            $result = [List[PSScriptBuilderSourceLocation]]::new()

            foreach ($component in $data.Components) {
                $result.Add([PSScriptBuilderSourceLocation]::new(
                    $component.ComponentName,
                    $component.ComponentType,
                    $component.SourceFile,
                    $component.SourceLineNumber,
                    $component.ComponentLineNumber,
                    $component.OutputLineNumber,
                    $component.Offset
                ))
            }

            $lineCount = [int] $data.OutputLineCount

            Write-Verbose "  Source map read: $($result.Count) component(s)"

            return [PSScriptBuilderSourceMapData]::new(
                $data.OutputPath,
                $data.OutputHash,
                $lineCount,
                $result.ToArray()
            )
        }
        catch [FileNotFoundException] {
            # FileNotFoundException inherits IOException. Without this block, a race condition
            # (file deleted between File.Exists() and File.ReadAllText()) would cause the catch
            # below to wrap the FileNotFoundException inside a new IOException, losing the type.
            throw
        }
        catch {
            $format  = "Failed to read source map from: {0}. Error: {1}"
            $message = $format -f $sidecarPath, $_.Exception.Message
            throw [IOException]::new($message, $_.Exception)
        }
    }

    <#
    .SYNOPSIS
        Reads only the output script hash from the sidecar file.
    .DESCRIPTION
        The ReadOutputHash method delegates to ReadSourceMapData and returns the stored
        SHA-256 hash of the output script. Throws FileNotFoundException if the sidecar
        file does not exist.
    .PARAMETER sidecarPath
        The absolute path to the sidecar file.
    .OUTPUTS
        Returns the SHA256 hash of the output script at the time the source map was created as string.
    #>
    static [string] ReadOutputHash([string] $sidecarPath) {
        return ([PSScriptBuilderSourceMapFileManager]::ReadSourceMapData($sidecarPath)).OutputHash
    }

    <#
    .SYNOPSIS
        Reads only the total output line count from the sidecar file.
    .DESCRIPTION
        The ReadOutputLineCount method delegates to ReadSourceMapData and returns the stored
        line count of the output script. Throws FileNotFoundException if the sidecar file
        does not exist.
    .PARAMETER sidecarPath
        The absolute path to the sidecar file.
    .OUTPUTS
        Returns the line count of the output script at the time the source map was created as int.
    #>
    static [int] ReadOutputLineCount([string] $sidecarPath) {
        return ([PSScriptBuilderSourceMapFileManager]::ReadSourceMapData($sidecarPath)).OutputLineCount
    }

    <#
    .SYNOPSIS
        Checks whether a sidecar file exists at the given path.
    .DESCRIPTION
        The SourceMapExists method returns $true if the sidecar file exists at sidecarPath,
        $false otherwise (including when sidecarPath is null or empty).
    .PARAMETER sidecarPath
        The absolute path to the sidecar file.
    .OUTPUTS
        Returns $true if the sidecar file exists at sidecarPath, $false otherwise.
    #>
    static [bool] SourceMapExists([string] $sidecarPath) {
        if ([string]::IsNullOrWhiteSpace($sidecarPath)) {
            return $false
        }

        return [File]::Exists($sidecarPath)
    }
    #endregion Static Methods
}
#endregion Class PSScriptBuilderSourceMapFileManager
